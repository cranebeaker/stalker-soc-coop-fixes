"""Give every dialog phrase of our patches that has no subtitle hook one (patch english_subtitles).

The mod shows a spoken dialog phrase as a PDA row / bottom subtitle through coop_pda_archive_sync.emit_phrase, which is called by an <action> of the
phrase (stock: coop_pda_phrases.say__<text id>, our SoC patches: generated coop_soc_*_say scripts). Phrases of the other patches (repeatable quests, Garbage,
Military, Mole, Monolith) had none. This tool adds <action>coop_subs_say.sp_<n></action> right after the <text> of each such phrase in the patch's own dialog
file and writes patches\\english_subtitles\\gamedata\\scripts\\coop_subs_say.script with the matching functions.

  python tools\\gen_subs_say.py [--dry-run]

Safe to run again: phrases that already have a say/emit action (including ours) are skipped, and the script is regenerated from the files as they are.
Speaker of a phrase (who talks, for the caption): breadth first from the first phrase of each dialog, depth 0 = the player, then it alternates.
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PATCHES = os.path.join(os.path.dirname(HERE), "patches")
OUT = os.path.join(PATCHES, "english_subtitles", "gamedata", "scripts", "coop_subs_say.script")
HOOK = re.compile(r"<action>[^<]*(say__|\.say_|emit_phrase|coop_subs_say\.sp_)[^<]*</action>")


def roles_of(dialog_body):
    """phrase id -> 'actor' | 'npc' by depth in the <next> tree (first phrase = the player's)."""
    phrases = {}
    for m in re.finditer(r'<phrase\s+id="([^"]*)"[^>]*>(.*?)</phrase>', dialog_body, re.S):
        phrases[m.group(1)] = re.findall(r"<next>([^<]*)</next>", m.group(2))
    roles = {}
    if "0" in phrases:
        level, depth = ["0"], 0
        while level:
            nxt = []
            for pid in level:
                if pid in roles:
                    continue
                roles[pid] = "actor" if depth % 2 == 0 else "npc"
                nxt.extend(phrases.get(pid, []))
            level, depth = nxt, depth + 1
    return roles


def main():
    dry = "--dry-run" in sys.argv
    by_n = {}           # n -> (text id, role): our hooks already in the files, kept on every run
    todo = []           # (file, dialog start, insert offset in the dialog body, text id, role): phrases that still have no hook
    files = sorted(glob.glob(os.path.join(PATCHES, "*", "gamedata", "configs", "gameplay", "dialogs_coop_*.xml")))
    raws = {}
    for p in files:
        if os.sep + "wip" in p:
            continue
        raw = open(p, "rb").read().decode("latin-1")
        raws[p] = raw
        for dm in re.finditer(r"<dialog\b[^>]*>.*?</dialog>", raw, re.S):
            body = dm.group(0)
            roles = roles_of(body)
            for pm in re.finditer(r'<phrase\s+id="([^"]*)"[^>]*>(.*?)</phrase>', body, re.S):
                inner = pm.group(2)
                tm = re.search(r"<text>([^<]*)</text>", inner)
                if not tm:
                    continue
                tid = tm.group(1).strip()
                if not tid:
                    continue
                role = roles.get(pm.group(1), "npc")
                ours = re.search(r"coop_subs_say\.sp_(\d+)", inner)
                if ours:
                    by_n[int(ours.group(1))] = (tid, role)
                elif not HOOK.search(inner):
                    todo.append((p, dm.start(), pm.start(2) + tm.end(), tid, role))
    # number the new ones after the highest existing number and edit the files (last insert first so offsets stay valid)
    nxt = max(by_n) + 1 if by_n else 1
    per_file = {}
    for p, dstart, off, tid, role in todo:
        by_n[nxt] = (tid, role)
        per_file.setdefault(p, []).append((dstart + off, "<action>coop_subs_say.sp_%d</action>" % nxt))
        nxt += 1
    changed = {}
    for p, ins in per_file.items():
        res = raws[p]
        for at, txt in sorted(ins, reverse=True):
            res = res[:at] + txt + res[at:]
        changed[p] = (res, len(ins))
    entries = [(n, by_n[n][0], by_n[n][1]) for n in sorted(by_n)]
    for p, (res, added) in changed.items():
        print("%-60s +%d hooks" % (os.path.relpath(p, PATCHES), added))
        if not dry:
            open(p, "wb").write(res.encode("latin-1"))
    print("total", len(entries), "phrases hooked")
    lines = [
        "-------------------------------------------------------------------------------------------------------",
        "-- GENERATED by tools\\gen_subs_say.py (patch english_subtitles): the subtitle hook of dialog phrases of our patches that had none",
        "-- (repeatable quests, Garbage, Military, Mole, Monolith). Same helper calls as the generated coop_soc_*_say scripts.",
        "-------------------------------------------------------------------------------------------------------",
        "",
        "local T = {",
    ]
    for n, tid, role in entries:
        lines.append('\t[%d] = { "%s", "%s" },' % (n, tid, role))
    lines += [
        "}",
        "",
        "local function emit(n, first, second)",
        "\tlocal e = T[n]",
        "\tif e == nil then return end",
        "\tpcall(function() coop_pda_phrases.phrase_speaker[e[1]] = e[2] end)",
        "\tpcall(function() coop_pda_archive_sync.emit_phrase(first, second, e[1]) end)",
        "end",
        "",
    ]
    for n, tid, role in entries:
        lines.append("function sp_%d(a, b) emit(%d, a, b) end" % (n, n))
    text = "\n".join(lines) + "\n"
    if not dry:
        open(OUT, "w", encoding="latin-1", newline="").write(text)
        print("written", os.path.relpath(OUT, PATCHES))


if __name__ == "__main__":
    main()
